-- --------------------------------------------
-- Table: students
-- --------------------------------------------
CREATE TABLE students (
    id INT AUTO_INCREMENT PRIMARY KEY,
    roll_no VARCHAR(20) UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    father_name VARCHAR(150),
    phone VARCHAR(20),
    address TEXT,
    date_of_birth DATE,
    gender ENUM('male','female') DEFAULT 'male',
    class_id INT,
    admission_date DATE,
    status ENUM('active','inactive') DEFAULT 'active',
    advance_balance DECIMAL(10,2) DEFAULT 0.00,
    FOREIGN KEY (class_id) REFERENCES classes(id)
);

-- --------------------------------------------
-- Table: fee_vouchers
-- --------------------------------------------
CREATE TABLE fee_vouchers (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT,
    fee_month TINYINT NOT NULL,
    fee_year YEAR NOT NULL,
    fee_amount DECIMAL(10,2) NOT NULL,
    discount DECIMAL(10,2) DEFAULT 0,
    previous_dues DECIMAL(10,2) DEFAULT 0,
    total_amount DECIMAL(10,2) NOT NULL,
    paid_amount DECIMAL(10,2) DEFAULT 0,
    status ENUM('unpaid','partial','paid') DEFAULT 'unpaid',
    generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY unique_voucher (student_id, fee_month, fee_year),
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE
);

-- --------------------------------------------
-- Table: fee_payments
-- --------------------------------------------
CREATE TABLE fee_payments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    voucher_id INT,
    student_id INT,
    amount_paid DECIMAL(10,2) NOT NULL,
    payment_date DATE NOT NULL,
    payment_method ENUM('cash','bank_transfer','cheque') DEFAULT 'cash',
    received_by VARCHAR(100),
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (voucher_id) REFERENCES fee_vouchers(id) ON DELETE CASCADE
);

-- --------------------------------------------
-- Table: teachers
-- --------------------------------------------
CREATE TABLE teachers (
    id INT AUTO_INCREMENT PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(100),
    cnic VARCHAR(20),
    address TEXT,
    joining_date DATE,
    monthly_salary DECIMAL(10,2) DEFAULT 0,
    status ENUM('active','inactive') DEFAULT 'active',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- --------------------------------------------
-- Table: salary_payments
-- --------------------------------------------
CREATE TABLE salary_payments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    teacher_id INT,
    salary_month TINYINT NOT NULL,
    salary_year YEAR NOT NULL,
    salary_amount DECIMAL(10,2) NOT NULL,
    paid_amount DECIMAL(10,2) DEFAULT 0,
    remaining DECIMAL(10,2) DEFAULT 0,
    payment_date DATE,
    payment_method ENUM('cash','bank_transfer','cheque') DEFAULT 'cash',
    notes TEXT,
    status ENUM('unpaid','partial','paid') DEFAULT 'unpaid',
    UNIQUE KEY unique_salary (teacher_id, salary_month, salary_year),
    FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE
);

-- --------------------------------------------
-- Table: attendance
-- --------------------------------------------
CREATE TABLE attendance (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT,
    class_id INT,
    attendance_date DATE NOT NULL,
    status ENUM('present','absent','leave') DEFAULT 'present',
    UNIQUE KEY unique_attendance (student_id, attendance_date),
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE
);

